package storage

import (
	"context"
	"os"
	"path/filepath"
	"strings"

	"github.com/gogf/gf/v2/errors/gerror"
	"github.com/gogf/gf/v2/frame/g"
)

// Local stores objects in a directory that the gateway serves under a URL
// prefix. It is for development only: files live on one machine.
type Local struct {
	dir     string
	baseURL string
}

// NewLocal returns a local store rooted at dir, whose objects are reachable
// under baseURL. The directory is created up front because the gateway serves
// it statically, and GoFrame refuses to serve a directory that does not exist.
func NewLocal(dir, baseURL string) (*Local, error) {
	if dir == "" || baseURL == "" {
		return nil, gerror.New("storage.local.dir and storage.local.baseUrl are required")
	}
	abs, err := filepath.Abs(dir)
	if err != nil {
		return nil, gerror.Wrap(err, "resolve storage.local.dir")
	}
	if err := os.MkdirAll(abs, 0o755); err != nil {
		return nil, gerror.Wrap(err, "create storage.local.dir")
	}
	return &Local{dir: abs, baseURL: strings.TrimRight(baseURL, "/")}, nil
}

func NewLocalFromConfig(ctx context.Context) (*Local, error) {
	dir, err := g.Cfg().Get(ctx, "storage.local.dir", "./uploads")
	if err != nil {
		return nil, gerror.Wrap(err, "read storage.local.dir")
	}
	baseURL, err := g.Cfg().Get(ctx, "storage.local.baseUrl", "http://127.0.0.1:8299/files")
	if err != nil {
		return nil, gerror.Wrap(err, "read storage.local.baseUrl")
	}
	return NewLocal(dir.String(), baseURL.String())
}

// Dir is the directory to serve statically.
func (l *Local) Dir() string { return l.dir }

func (l *Local) Name() string { return "local" }

func (l *Local) Put(_ context.Context, key string, data []byte, _ string) (string, error) {
	path, err := l.path(key)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", gerror.Wrap(err, "create upload directory")
	}
	// O_EXCL: never overwrite an existing object, mirroring Qiniu's insertOnly.
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return "", gerror.Wrap(err, "create object")
	}
	if _, err := f.Write(data); err != nil {
		_ = f.Close()
		_ = os.Remove(path)
		return "", gerror.Wrap(err, "write object")
	}
	if err := f.Close(); err != nil {
		_ = os.Remove(path)
		return "", gerror.Wrap(err, "close object")
	}
	return l.baseURL + "/" + key, nil
}

func (l *Local) Delete(_ context.Context, key string) error {
	path, err := l.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
		return gerror.Wrap(err, "delete object")
	}
	return nil
}

// path maps a key to a file and refuses anything that would escape the
// directory. Keys are generated by the gateway, so this is defence in depth.
func (l *Local) path(key string) (string, error) {
	path := filepath.Join(l.dir, filepath.FromSlash(key))
	if !strings.HasPrefix(path, l.dir+string(filepath.Separator)) {
		return "", gerror.Newf("object key %q escapes the storage directory", key)
	}
	return path, nil
}
